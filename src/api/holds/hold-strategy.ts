import { PoolClient } from 'pg';

export interface HoldRow {
  id: string;
  event_id: string;
  user_id: string;
  idempotency_key: string;
  request_hash: string;
  seat_ids: string[]; // bigint[] comes back from pg as strings
  amount_paise: number;
  status: 'active' | 'booked' | 'released' | 'expired';
  expires_at: Date;
  created_at: Date;
  updated_at: Date;
}

// Everything a strategy needs to try to hold seats.
export interface HoldAttempt {
  holdId: string; // generated by the app, so the Redis gate can tag its keys with it
  eventId: string;
  userId: string;
  idempotencyKey: string;
  requestHash: string;
  seatIds: number[]; // sorted ascending
  holdSeconds: number;
}

export type StrategyResult =
  | { kind: 'held'; hold: HoldRow }
  | { kind: 'unavailable'; seatIds: number[] } // someone else has these seats
  | { kind: 'invalid_seats'; seatIds: number[] } // not seats of this event
  | { kind: 'key_taken' }; // a concurrent request with the same idempotency key won

/**
 * One way of making "check the seats are free" and "mark them held" a single atomic step.
 * Three implementations, chosen with HOLD_STRATEGY, so they can be load-tested against
 * each other: pessimistic.ts, optimistic.ts, redis-gate.ts.
 */
export interface HoldStrategy {
  readonly name: 'pessimistic' | 'optimistic' | 'redis';
  hold(attempt: HoldAttempt): Promise<StrategyResult>;
  // Called after seats go back on sale or get booked, so a cache in front of Postgres
  // (the Redis gate) can follow. Best effort: Postgres stays the source of truth.
  afterRelease(eventId: string, seatIds: number[], holdId: string): Promise<void>;
  afterBooking(eventId: string, seatIds: number[]): Promise<void>;
}

// A seat counts as free if it's available, or held by a hold that has expired.
// Holds expire lazily: nothing flips them back on time, every check just includes this.
export const SEAT_IS_FREE_SQL = `(status = 'available' OR (status = 'held' AND held_until <= now()))`;

export interface SeatState {
  id: string;
  event_id: string;
  price_paise: number;
  version: number;
  free: boolean;
}

export type SeatCheck = { kind: 'ok'; amountPaise: number } | Extract<StrategyResult, { kind: 'unavailable' | 'invalid_seats' }>;

// Checks seat rows read by a strategy: all exist, all belong to the event, all free.
export function checkSeats(attempt: HoldAttempt, rows: SeatState[]): SeatCheck {
  const found = new Map(rows.map((r) => [Number(r.id), r]));
  const invalid = attempt.seatIds.filter((id) => found.get(id)?.event_id !== attempt.eventId);
  if (invalid.length > 0) return { kind: 'invalid_seats', seatIds: invalid };

  const taken = attempt.seatIds.filter((id) => !found.get(id)!.free);
  if (taken.length > 0) return { kind: 'unavailable', seatIds: taken };

  return { kind: 'ok', amountPaise: rows.reduce((sum, r) => sum + r.price_paise, 0) };
}

// Inserts the hold row. Returns null if a concurrent request with the same idempotency key
// already inserted one. (The id is derived from the key, so that conflict can show up on
// the primary key or on UNIQUE (user_id, idempotency_key); DO NOTHING covers both.)
export async function insertHold(client: PoolClient, attempt: HoldAttempt, amountPaise: number): Promise<HoldRow | null> {
  const { rows } = await client.query<HoldRow>(
    `INSERT INTO holds (id, event_id, user_id, idempotency_key, request_hash, seat_ids, amount_paise, expires_at)
     VALUES ($1, $2, $3, $4, $5, $6, $7, now() + make_interval(secs => $8))
     ON CONFLICT DO NOTHING
     RETURNING *`,
    [
      attempt.holdId,
      attempt.eventId,
      attempt.userId,
      attempt.idempotencyKey,
      attempt.requestHash,
      attempt.seatIds,
      amountPaise,
      attempt.holdSeconds,
    ],
  );
  return rows[0] ?? null;
}
